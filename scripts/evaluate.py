"""Tune the fusion on validation data, then compare three systems once on the test set.

Systems: ML only, rules only, hybrid (ML + rules). Each system's decision threshold (and the
hybrid's alpha) is chosen on the validation set; the test set is only used for the final
report. Run with ``--no-test`` while developing to look at validation results only.

Outputs: models/fusion_params.json, reports/metrics_test.json, reports/confusion_matrix.png,
reports/error_analysis.md.

Usage:
    python scripts/evaluate.py [--no-test]
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import f1_score, recall_score

from smishguard import config
from smishguard.analyzer import Analyzer
from smishguard.data.anonymize import mask_honorific_names
from smishguard.data.normalize import defang
from smishguard.evaluation import (
    TuningResult,
    bootstrap_ci,
    choose_high_threshold,
    tune_fusion,
    tune_threshold,
)
from smishguard.features.reasons import evaluate_rules, rule_score
from smishguard.metrics import classification_metrics
from smishguard.model.predict import predict_proba
from smishguard.scoring.fusion import FusionParams, save_fusion_params

logger = logging.getLogger("evaluate")

SYSTEMS = ("ml_only", "rules_only", "hybrid")


def load_split(name: str) -> pd.DataFrame:
    """Read a processed split."""
    path = config.PROCESSED_DIR / f"{name}.csv"
    if not path.exists():
        raise FileNotFoundError(f"{path} not found. Run `python scripts/build_dataset.py` first.")
    return pd.read_csv(path, keep_default_na=False)


def score_split(analyzer: Analyzer, data: pd.DataFrame) -> pd.DataFrame:
    """Add ML probability, rule score and fired rule codes to a split."""
    prepared = data["text"].map(analyzer.prepare)
    reasons = prepared.map(evaluate_rules)
    return data.assign(
        ml=predict_proba(analyzer.model, prepared),
        rules=reasons.map(rule_score),
        rule_codes=reasons.map(lambda rs: ", ".join(r.code for r in rs) or "-"),
    )


def system_scores(scored: pd.DataFrame, system: str, alpha: float) -> np.ndarray:
    """Score used by each system for its decision."""
    if system == "ml_only":
        return scored["ml"].to_numpy()
    if system == "rules_only":
        return scored["rules"].to_numpy()
    return alpha * scored["ml"].to_numpy() + (1 - alpha) * scored["rules"].to_numpy()


def tune_all(val: pd.DataFrame) -> dict[str, TuningResult]:
    """Choose thresholds (and alpha for the hybrid) on validation data."""
    y = val["label"]
    return {
        "ml_only": tune_threshold(y, val["ml"]),
        "rules_only": tune_threshold(y, val["rules"]),
        "hybrid": tune_fusion(y, val["ml"], val["rules"]),
    }


def write_json(path: Path, payload: dict) -> None:
    """Write pretty JSON with LF line endings."""
    path.parent.mkdir(parents=True, exist_ok=True)
    text = json.dumps(payload, indent=2, ensure_ascii=False) + "\n"
    path.write_text(text, encoding="utf-8", newline="\n")


def plot_confusion_matrices(results: dict[str, dict], path: Path) -> None:
    """Save one confusion matrix per system side by side."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, axes = plt.subplots(1, len(SYSTEMS), figsize=(12, 3.8))
    for ax, system in zip(axes, SYSTEMS, strict=True):
        m = results[system]["metrics"]
        matrix = np.array([[m["tn"], m["fp"]], [m["fn"], m["tp"]]])
        ax.imshow(matrix, cmap="Blues", vmin=0, vmax=matrix.sum())
        for (i, j), value in np.ndenumerate(matrix):
            color = "white" if value > matrix.sum() / 2 else "black"
            ax.text(j, i, str(value), ha="center", va="center", fontsize=14, color=color)
        ax.set_xticks([0, 1], ["legitimate", "malicious"])
        ax.set_yticks([0, 1], ["legitimate", "malicious"])
        ax.set_xlabel("predicted")
        ax.set_ylabel("actual")
        ax.set_title(
            f"{system.replace('_', ' ')}\nF1 {m['f1']:.3f} | FPR {m['false_positive_rate']:.3f}"
        )
    fig.suptitle(f"Test set confusion matrices (n = {matrix.sum()})")
    fig.tight_layout()
    fig.savefig(path, dpi=120)
    plt.close(fig)


def _excerpt(text: str) -> str:
    text = mask_honorific_names(defang(text)).replace("|", "/")
    limit = config.ERROR_EXAMPLE_MAX_CHARS
    return text if len(text) <= limit else text[: limit - 1] + "…"


def write_error_analysis(
    test: pd.DataFrame, tuned: dict[str, TuningResult], curated: pd.DataFrame, path: Path
) -> None:
    """Write a Markdown report with hybrid errors and a curated per-category breakdown."""
    hybrid = tuned["hybrid"]
    lines = [
        "# Error analysis",
        "",
        "Generated by `scripts/evaluate.py`. Messages are PII-masked (including names after",
        f"an honorific), links defanged, truncated to {config.ERROR_EXAMPLE_MAX_CHARS} characters.",
        "",
        f"Hybrid system: alpha = {hybrid.alpha}, threshold = {hybrid.threshold}.",
        "",
    ]
    flagged = {s: test[f"pred_{s}"] == 1 for s in SYSTEMS}
    for title, mask in (
        (
            "False positives (legitimate flagged as malicious)",
            flagged["hybrid"] & (test["label"] == 0),
        ),
        ("False negatives (malicious missed)", ~flagged["hybrid"] & (test["label"] == 1)),
    ):
        rows = test[mask].sort_values("risk", ascending=False)
        lines += [f"## {title}: {len(rows)}", ""]
        if rows.empty:
            lines += ["None.", ""]
            continue
        lines += [
            "| Message | ML p | Rule score | Risk | Rules fired | ML-only also wrong | Length |",
            "|---|---:|---:|---:|---|:---:|---:|",
        ]
        for _, row in rows.iterrows():
            ml_wrong = row["pred_ml_only"] != row["label"]
            lines.append(
                f"| {_excerpt(row['text'])} | {row['ml']:.2f} | {row['rules']:.2f} | "
                f"{row['risk']:.2f} | {row['rule_codes']} | {'yes' if ml_wrong else 'no'} | "
                f"{len(row['text'])} |"
            )
        lines.append("")

    rules_threshold = tuned["rules_only"].threshold
    lines += [
        "## Curated examples by category (informational)",
        "",
        "The curated messages are part of the **training** set, so ML results on them are not",
        "meaningful and are omitted. The rule engine is not trained, but its keyword lists were",
        "written with these scam types in mind; treat this table as a coverage check, not as",
        "an unbiased evaluation.",
        f"Detection = rule score >= {rules_threshold} (the rules-only threshold).",
        "",
        "| Category | Label | Messages | Mean rule score | Detected by rules |",
        "|---|---|---:|---:|---:|",
    ]
    curated = curated.assign(detected=curated["rules"] >= rules_threshold)
    for (category, label), group in curated.groupby(["category", "label"]):
        label_name = "malicious" if label == 1 else "legitimate"
        lines.append(
            f"| {category} | {label_name} | {len(group)} | {group['rules'].mean():.2f} | "
            f"{group['detected'].mean():.0%} |"
        )
    lines.append("")

    if config.ERROR_NOTES_PATH.exists():
        lines += [config.ERROR_NOTES_PATH.read_text(encoding="utf-8").strip(), ""]
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main() -> int:
    """Entry point. Returns a process exit code."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--no-test", action="store_true", help="only tune and report validation")
    args = parser.parse_args()

    try:
        analyzer = Analyzer.from_files()
        train, val = load_split("train"), load_split("val")
        test = None if args.no_test else load_split("test")
    except FileNotFoundError as exc:
        logger.error("%s", exc)
        return 1

    val = score_split(analyzer, val)
    tuned = tune_all(val)
    hybrid = tuned["hybrid"]
    hybrid_val_scores = system_scores(val, "hybrid", hybrid.alpha)
    high = choose_high_threshold(val["label"], hybrid_val_scores, hybrid.threshold)
    params = FusionParams(
        alpha=hybrid.alpha, medium_threshold=hybrid.threshold, high_threshold=high
    )
    for system, result in tuned.items():
        logger.info(
            "val %-10s alpha=%s threshold=%.2f F1=%.4f FPR=%.4f",
            system,
            result.alpha,
            result.threshold,
            result.metrics["f1"],
            result.metrics["false_positive_rate"],
        )
    logger.info("Fusion params: %s", params)
    if test is None:
        logger.info("--no-test: nothing written")
        return 0

    save_fusion_params(params)

    # ---- The single use of the test set ----
    test = score_split(analyzer, test)
    test_results: dict[str, dict] = {}
    for system in SYSTEMS:
        scores = system_scores(test, system, hybrid.alpha)
        predictions = (scores >= tuned[system].threshold).astype(int)
        test[f"pred_{system}"] = predictions
        test_results[system] = {
            "threshold": tuned[system].threshold,
            "metrics": classification_metrics(test["label"], predictions, scores),
            "f1_ci95": bootstrap_ci(
                test["label"], predictions, lambda a, b: f1_score(a, b, zero_division=0)
            ),
            "recall_ci95": bootstrap_ci(
                test["label"], predictions, lambda a, b: recall_score(a, b, zero_division=0)
            ),
        }
        logger.info("test %-10s %s", system, test_results[system]["metrics"])
    test["risk"] = system_scores(test, "hybrid", hybrid.alpha)

    metadata = json.loads(config.MODEL_METADATA_PATH.read_text(encoding="utf-8"))
    report = {
        "description": "Thresholds and alpha tuned on validation; test set used once.",
        "model": {k: metadata[k] for k in ("model_name", "model_version")},
        "fusion_params": {
            "alpha": params.alpha,
            "medium_threshold": params.medium_threshold,
            "high_threshold": params.high_threshold,
        },
        "test_set": {
            "rows": len(test),
            "legitimate": int((test["label"] == 0).sum()),
            "malicious": int((test["label"] == 1).sum()),
            "sources": sorted(test["source"].unique().tolist()),
        },
        "validation": {
            system: {"alpha": r.alpha, "threshold": r.threshold, "metrics": r.metrics}
            for system, r in tuned.items()
        },
        "test": test_results,
        "test_risk_levels": {
            level: int(count)
            for level, count in pd.cut(
                test["risk"],
                bins=[-np.inf, params.medium_threshold, params.high_threshold, np.inf],
                right=False,
                labels=["low", "medium", "high"],
            )
            .value_counts()
            .sort_index()
            .items()
        },
    }
    write_json(config.TEST_METRICS_PATH, report)
    plot_confusion_matrices(test_results, config.CONFUSION_MATRIX_PATH)

    curated = score_split(analyzer, train[train["source"] != config.SOURCE_TURKISHSMS])
    write_error_analysis(test, tuned, curated, config.ERROR_ANALYSIS_PATH)
    logger.info("Wrote reports to %s", config.REPORTS_DIR.relative_to(config.PROJECT_ROOT))
    return 0


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")
    sys.exit(main())
